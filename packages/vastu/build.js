// Builds the package twice: dist/dev keeps the developer warnings, dist/prod drops them.
// package.json "exports" serves dev under the "development" condition and prod by default.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

// Every folder in src/ except core/ is a component with its own entry point. Keep package.json
// "exports" and src/all.ts in step with them, so a new component can't be left out.
const componentDirs = fs.readdirSync('src', { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== 'core').map((d) => d.name).sort();
fs.writeFileSync('src/all.ts', `// Generated by build.js: registers every Vastu component.\n${componentDirs.map((c) => `export * from './${c}/index.js';`).join('\n')}\n`);
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const entry = (name) => ({ types: `./dist/dev/${name}.d.ts`, development: `./dist/dev/${name}.js`, default: `./dist/prod/${name}.js` });
pkg.exports = Object.fromEntries([
  ...componentDirs.map((c) => [`./${c}`, entry(`${c}/index`)]),
  ['./all', entry('all')],
  ['./custom-elements.json', './custom-elements.json'],
]);
pkg.sideEffects = ['./dist/*/*/index.js', './dist/*/all.js'];
fs.writeFileSync('package.json', JSON.stringify(pkg, null, 2) + '\n');

fs.rmSync('dist', { recursive: true, force: true });
execFileSync('npx', ['tsc', '-p', 'tsconfig.json'], { stdio: 'inherit' });
fs.cpSync('dist/dev', 'dist/prod', { recursive: true });
fs.writeFileSync('dist/prod/core/dev-mode.js', 'export const DEV_MODE = false;\n');
// Replace the warning helpers outright, so no message text reaches production bundles.
fs.writeFileSync('dist/prod/core/warn.js', 'export function devWarn() {}\nexport function checkTokensLoaded() {}\n');
for (const f of fs.readdirSync('dist/prod', { recursive: true })) {
  if (String(f).endsWith('.map') || String(f).endsWith('.d.ts')) fs.rmSync(`dist/prod/${f}`);
}
execFileSync('npx', ['cem', 'analyze', '--config', 'cem.config.js'], { stdio: 'inherit' });

// Every component folder must have a documented custom element in the manifest. (A JSDoc block
// separated from its class drops the component silently, so check explicitly.)
const manifest = JSON.parse(fs.readFileSync('custom-elements.json', 'utf8'));
const tags = new Set(manifest.modules.flatMap((m) => m.declarations ?? []).map((d) => d.tagName).filter(Boolean));
const missing = componentDirs.filter((c) => !tags.has(`va-${c}`));
if (missing.length) {
  console.error(`The manifest has no documented element for: ${missing.map((c) => `va-${c} (src/${c}/)`).join(', ')}. Check that its JSDoc block sits directly above the class.`);
  process.exit(1);
}
