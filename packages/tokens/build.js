// Builds each brand's DTCG token files into CSS custom properties, JSON and TypeScript.
// Usage: node build.js
import StyleDictionary from 'style-dictionary';
import fs from 'node:fs/promises';
import path from 'node:path';

// The first brand is the default: it also applies to a page with no data-va-brand.
const BRANDS = ['vastu', 'lekha'];
const MODES = ['light', 'dark', 'high-contrast'];
const DIST = 'dist';

// DTCG 2025.10 writes dimensions and durations as { value, unit } objects.
StyleDictionary.registerTransform({
  name: 'vastu/dtcg-units',
  type: 'value',
  transitive: true,
  filter: (token) => typeof (token.$value ?? token.value) === 'object' && !Array.isArray(token.$value ?? token.value),
  transform: (token) => {
    const v = token.$value ?? token.value;
    return `${v.value}${v.unit}`;
  },
});

const TRANSFORMS = ['name/kebab', 'vastu/dtcg-units', 'color/css', 'fontFamily/css'];

async function resolve(brand, mode) {
  const sd = new StyleDictionary({
    source: ['src/reference.tokens.json', `src/brands/${brand}/base.tokens.json`, `src/brands/${brand}/${mode}.tokens.json`],
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: { prefix: 'va', transforms: TRANSFORMS } },
  });
  const dictionary = await sd.getPlatformTokens('css');
  // System tokens only: reference tokens (the source file) are not exposed to components.
  return dictionary.allTokens.filter((t) => !t.filePath.endsWith('reference.tokens.json'));
}

const decls = (tokens, pick = () => true) =>
  tokens.filter(pick).map((t) => `  --${t.name}: ${t.$value ?? t.value};`).join('\n');

const isColor = (t) => (t.$type ?? t.type) === 'color';

await fs.mkdir(DIST, { recursive: true });
const catalogue = {};

for (const brand of BRANDS) {
  const modes = {};
  for (const mode of MODES) modes[mode] = await resolve(brand, mode);
  // This brand applies where data-va-brand names it, and on a page with no data-va-brand at all.
  // A mode applies on the brand's element or on any element inside it.
  const scopes = [':root:not([data-va-brand])', `[data-va-brand="${brand}"]`];
  const sel = (suffix) => scopes.map((s) => `${s}${suffix}`).join(',\n');
  const inMode = (mode) => scopes.flatMap((s) => [`${s}[data-va-mode="${mode}"]`, `${s} [data-va-mode="${mode}"]`]).join(',\n');
  const indent = (text) => text.replace(/^/gm, '  ');
  const css = [
    [
      `/* Vastu tokens, brand "${brand}". Generated by packages/tokens/build.js; do not edit.`,
      `   Applies to elements with data-va-brand="${brand}", and to the whole page when no element sets`,
      `   data-va-brand (load one brand file per page, or set data-va-brand when you load several).`,
      `   Light is the default mode. Set data-va-mode="light|dark|high-contrast" on the same element or`,
      `   one inside it; without it the mode follows prefers-color-scheme and prefers-contrast. */`,
    ].join('\n'),
    `${sel('')} {\n  color-scheme: light;\n${decls(modes.light)}\n}`,
    `@media (prefers-color-scheme: dark) {\n${indent(sel(':not([data-va-mode])'))} {\n    color-scheme: dark;\n${indent(decls(modes.dark, isColor))}\n  }\n}`,
    `@media (prefers-contrast: more) {\n${indent(sel(':not([data-va-mode])'))} {\n    color-scheme: light;\n${indent(decls(modes['high-contrast'], isColor))}\n  }\n}`,
    ...MODES.map((mode) => `${inMode(mode)} {\n  color-scheme: ${mode === 'dark' ? 'dark' : 'light'};\n${decls(modes[mode], isColor)}\n}`),
    '',
  ].join('\n\n');
  await fs.writeFile(path.join(DIST, `${brand}.css`), css);

  const json = { brand, modes: {} };
  for (const mode of MODES) {
    json.modes[mode] = Object.fromEntries(modes[mode].map((t) => [t.path.join('.'), t.$value ?? t.value]));
  }
  await fs.writeFile(path.join(DIST, `${brand}.json`), JSON.stringify(json, null, 2) + '\n');

  for (const t of modes.light) {
    catalogue[t.path.join('.')] = {
      cssVar: `--${t.name}`,
      type: t.$type ?? t.type,
      description: t.$description ?? t.description ?? '',
    };
  }
}

await fs.writeFile(path.join(DIST, 'tokens.json'), JSON.stringify(catalogue, null, 2) + '\n');
const names = Object.values(catalogue).map((t) => `  | '${t.cssVar}'`).join('\n');
await fs.writeFile(path.join(DIST, 'index.d.ts'), `/** Every Vastu system token, as a CSS custom property name. */\nexport type TokenVar =\n${names};\n\nexport declare const tokens: Record<string, { cssVar: TokenVar; type: string; description: string }>;\nexport declare const brands: readonly ${JSON.stringify(BRANDS)}[number][];\nexport declare const modes: readonly ${JSON.stringify(MODES)}[number][];\n`);
await fs.writeFile(path.join(DIST, 'index.js'), `export const tokens = ${JSON.stringify(catalogue, null, 2)};\nexport const brands = ${JSON.stringify(BRANDS)};\nexport const modes = ${JSON.stringify(MODES)};\n`);
console.log(`Built ${BRANDS.length} brand(s) × ${MODES.length} modes, ${Object.keys(catalogue).length} system tokens.`);
